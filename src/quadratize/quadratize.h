// ============================================================================
// src/quadratize/quadratize.h
//
// Модуль quadratize: приведение полиномиальной системы ОДУ первого порядка
// к квадратичному виду путём введения вспомогательных переменных.
//
// Зависимости:
//   quadratize -> expression   (Expr, ExprPtr, фабрики, запросы)
//   quadratize -> input        (RawSystem, Equation, InitialCondition)
//   quadratize -> simplify     (Simplify, ExprEquals)
//
// Зачем. Численное интегрирование методом Тейлора в Solver эффективнее,
// если RHS системы содержит только мономы степени <= 2. Любая
// полиномиальная система сводится к квадратичной введением дополнительных
// переменных: каждая новая переменная отвечает за моном степени >= 3,
// а её уравнение динамики квадратично (правило произведения).
//
// Отвечает за:
//   - поиск в RHS системы мономов степени >= 3;
//   - введение вспомогательных переменных q_N для этих мономов;
//   - переписывание исходных RHS так, чтобы все мономы имели степень <= 2;
//   - добавление уравнений динамики новых переменных;
//   - вычисление начальных значений новых переменных по исходным IC;
//   - возврат карты {имя_новой_переменной -> её определение}.
//
// Что модуль НЕ делает:
//   - не полиномизирует систему (это Polynomize);
//   - не понижает порядок (это OrderReducer);
//   - не нормализует (это NormalizeSystem);
//   - не решает получившуюся систему;
//   - не делает минимальную квадратизацию (минимум числа переменных —
//     NP-hard в общем случае; здесь строится линейная цепочка,
//     не претендующая на оптимальность);
//   - не обрабатывает символьные IC (только числовые значения);
//   - не оптимизирует число переменных.
//
// ВАЖНО: Quadratize ожидает, что система уже первого порядка и
// полиномиальна (после Polynomize). Если это не так — QuadratizeError.
// ============================================================================
#pragma once

#include <map>
#include <stdexcept>
#include <string>

#include "core/expression.h"
#include "input/input.h"

namespace diffuri {

    // ============================================================================
    // ОШИБКИ КВАДРАТИЗАЦИИ
    // ============================================================================

    /**
     * @class QuadratizeError
     * @brief Ошибка этапа квадратизации.
     *
     * Типичные причины:
     *   - lhs уравнения не Derivative{f, 1} (система не первого порядка);
     *   - RHS не полиномиален (IsPolynomial == false);
     *   - коллизия имён вспомогательных переменных, не разрешаемая
     *     префиксом "_" (заняты и q_1, и _q_1);
     *   - разные t0 в начальных условиях (нельзя однозначно вычислить IC
     *     новых переменных);
     *   - внутреннее нарушение инвариантов алгоритма (страховка).
     */
    class QuadratizeError : public std::runtime_error {
    public:
        explicit QuadratizeError(const std::string& what);
    };

    // ============================================================================
    // КАРТА ВСПОМОГАТЕЛЬНЫХ ПЕРЕМЕННЫХ
    // ============================================================================

    /**
     * @brief Карта {имя_новой_переменной -> её определение}.
     *
     * Ключ — имя введённой переменной (q_1, q_2, ... или _q_1, _q_2, ...
     * при коллизии с уже существующими именами в системе).
     * Значение — выражение вида Mul(Function(a), Function(b)),
     * где a, b — имена существующих переменных (исходных или ранее
     * введённых вспомогательных). Смысл: новая переменная равна
     * произведению двух уже существующих переменных.
     *
     * Примеры:
     *   "q_1" -> Mul(Function("x"),   Function("x"))     // обозначает x^2
     *   "q_2" -> Mul(Function("x"),   Function("q_1"))   // обозначает x^3
     *   "q_3" -> Mul(Function("q_1"), Function("q_1"))   // обозначает x^4
     *
     * Значение НЕ упрощается через Simplify: даже для q_1 = x*x в карте
     * лежит именно Mul(Function("x"), Function("x")), а не Pow(Function,
     * Number(2)). Это оговорено в ТЗ (P5: «Mul(Function, Function)»)
     * и важно для диагностики и возможной обратной подстановки.
     *
     * Используется PipelineTrace для диагностики и (в будущем) обратной
     * подстановки при реконструкции «чистого» вида системы.
     * Для систем, уже квадратичных, карта пуста.
     */
    using QuadratizeAuxiliary = std::map<std::string, ExprPtr>;

    // ============================================================================
    // ГЛАВНАЯ ФУНКЦИЯ
    // ============================================================================

    /**
     * @brief Привести полиномиальную систему к квадратичному виду.
     *
     * Модифицирует sys in-place: переписывает RHS так, чтобы все мономы
     * имели степень <= 2, и добавляет уравнения динамики новых переменных.
     *
     * Алгоритм (линейная цепочка, не минимальная квадратизация):
     *   - для каждого монома M степени d >= 3 строится цепочка
     *     M = x_j · M', M' = x_j' · M'', ..., до монома степени <= 2;
     *   - каждая новая переменная — произведение двух уже существующих,
     *     поэтому её производная квадратична (правило произведения);
     *   - используется кэш {канон_монома -> имя переменной}, общий для
     *     всей системы (одна x^3 в разных уравнениях — одна переменная);
     *   - IC новых переменных вычисляются в порядке возрастания степени,
     *     только численно.
     *
     * Постусловие (при успешном возврате):
     *   - все eq.rhs квадратичны (IsQuadratic == true);
     *   - каждое eq.lhs — Derivative{f, 1};
     *   - sys.functions содержит все исходные имена плюс новые;
     *   - для каждой новой переменной q_i есть IC {q_i, 0, t0, value};
     *   - возвращаемая карта содержит все введённые переменные
     *     (и только их).
     *
     * @param sys Система. Модифицируется на месте.
     *
     * @return Карта {имя_новой_переменной -> её определение}. Пустая,
     *         если система уже квадратична (идемпотентность: повторный
     *         вызов на уже квадратичной системе — no-op).
     *
     * @throws QuadratizeError при нарушении входных инвариантов
     *         (см. описание класса QuadratizeError).
     */
    [[nodiscard]] QuadratizeAuxiliary Quadratize(RawSystem& sys);

    // ============================================================================
    // ВСПОМОГАТЕЛЬНОЕ (для тестов, отладки, диагностики)
    // ============================================================================

    /**
     * @brief Проверить, что выражение квадратично.
     *
     * Возвращает true, если выражение — полином степени <= 2,
     * построенный только из разрешённых конструкций:
     *   - Number;
     *   - Function;
     *   - Constant;
     *   - Binary{Add, Sub} с квадратичными операндами;
     *   - Binary{Mul} двух операндов, суммарная степень которых <= 2;
     *   - Binary{Pow} с Function-базой и Number(2) в показателе.
     *
     * Возвращает false при наличии:
     *   - Binary{Pow} со степенью >= 3 или с не-Number / отрицательным /
     *     дробным показателем;
     *   - Binary{Div};
     *   - Call;
     *   - Unary;
     *   - Derivative;
     *   - мономов степени >= 3, даже полученных через произведение
     *     (например, x^2 * y — степень 3).
     *
     * Примеры:
     *   x + 1        -> true
     *   x * y        -> true
     *   x^2          -> true
     *   x^2 + y^2    -> true
     *   x^3          -> false
     *   x^5          -> false
     *   x * y * z    -> false
     *   x^2 * y      -> false
     *   sin(x)       -> false
     *   1 / x        -> false
     */
    [[nodiscard]] bool IsQuadratic(const Expr& e);

} // namespace diffuri