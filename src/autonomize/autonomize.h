// ============================================================================
// src/autonomize/autonomize.h
//
// Модуль autonomize: приведение неавтономной системы ОДУ
// x' = f(x, t) к автономной x' = f(x, t), t' = 1 путём добавления
// независимой переменной t как обычной функции.
//
// Зависимости:
//   autonomize -> expression   (Expr, ExprPtr, фабрики, запросы)
//   autonomize -> input        (RawSystem, Equation, InitialCondition,
//                               CollectT0s)
//
// Зачем. Метод дополнительных переменных (МДП) в базовой постановке
// работает только с автономными системами (см. Бабаджанянц Л. К.,
// Брэгман К. М. «Алгоритм метода дополнительных переменных», 2012, §2.1).
// Любая неавтономная система x' = f(x, t) сводится к автономной введением
// независимой переменной t как дополнительной функции с тривиальной
// динамикой t' = 1. Это отдельный этап пайплайна, который должен
// выполняться до Polynomize и Quadratize.
//
// Что модуль НЕ делает:
//   - не трогает систему, в RHS которой t не встречается (no-op);
//   - не оптимизирует число уравнений;
//   - не обрабатывает символьные IC (все значения — double);
//   - не пытается автономизировать системы выше первого порядка
//     (это работа OrderReducer, который идёт до нас);
//   - не нормализует систему (это NormalizeSystem).
//
// ВАЖНО: Autonomize ожидает, что система уже нормализована и понижена
// до первого порядка (после NormalizeSystem + OrderReducer). Если
// это не так — AutonomizeError.
// ============================================================================
#pragma once

#include <map>
#include <stdexcept>
#include <string>

#include "core/expression.h"
#include "input/input.h"

namespace diffuri {

    // ========================================================================
    // ОШИБКИ АВТОНОМИЗАЦИИ
    // ========================================================================

    /**
     * @class AutonomizeError
     * @brief Ошибка этапа автономизации.
     *
     * Типичные причины:
     *   - lhs хотя бы одного уравнения не Derivative{f, 1}
     *     (система не первого порядка: забыт OrderReducer);
     *   - t встречается в RHS, но определить t0 не удаётся:
     *       * в системе нет ни одного начального условия (t0s.empty());
     *       * в IC встречается несколько разных t0 (t0s.size() > 1) —
     *         нельзя однозначно задать t(t0);
     *   - t уже присутствует в sys.functions «не нашим» уравнением
     *     (страховка; Validate обычно такое не пропускает).
     */
    class AutonomizeError : public std::runtime_error {
    public:
        explicit AutonomizeError(const std::string& what);
    };

    // ========================================================================
    // КАРТА ВСПОМОГАТЕЛЬНЫХ ПЕРЕМЕННЫХ
    // ========================================================================

    /**
     * @brief Карта {имя_новой_переменной -> её определение}.
     *
     * Для автономизации — либо пусто (система уже автономна, t не
     * встречается ни в одном RHS), либо ровно одна запись:
     *   "t" -> Number(t0)
     *
     * Смысл: независимая переменная t введена как обычная функция,
     * значение которой в точке t0 совпадает с самой точкой.
     *
     * Примеры:
     *   x' = t * x^2, x(0) = 1  ->  {"t" -> Number(0.0)}
     *   x' = t * x^2, x(2) = 1  ->  {"t" -> Number(2.0)}
     *
     * Используется PipelineTrace для диагностики и (в будущем) обратной
     * подстановки при реконструкции «чистого» вида системы.
     */
    using AutonomizeAuxiliary = std::map<std::string, ExprPtr>;

    // ========================================================================
    // ОСНОВНАЯ ФУНКЦИЯ
    // ========================================================================

    /**
     * @brief Привести неавтономную систему к автономной.
     *        Модифицирует sys in-place.
     *
     * Алгоритм:
     *   1. Проверить, что каждое eq.lhs — Derivative{f, 1}
     *      (иначе AutonomizeError).
     *   2. Обойти все RHS в поисках узла Function{sys.independent_variable}.
     *      Если t нигде не встречается — вернуть пустую карту,
     *      систему не трогать (no-op).
     *   3. Если система уже автономизирована (есть уравнение
     *      Derivative{t, 1} = Number(1.0) и IC для t) — вернуть пустую
     *      карту (идемпотентность).
     *   4. Собрать t0s = CollectT0s(sys):
     *        - пусто  -> AutonomizeError («нельзя определить t0»);
     *        - >1     -> AutonomizeError («разные t0 в IC»);
     *        - иначе t0 = *t0s.begin().
     *   5. Добавить уравнение Derivative{t, 1} = Number(1.0).
     *   6. Добавить IC {t, 0, t0, t0}.
     *   7. Зарегистрировать t в sys.functions.
     *   8. Вернуть {"t" -> Number(t0)}.
     *
     * @param sys Система. Модифицируется на месте.
     *
     * @return Карта {имя_новой_переменной -> её определение}. Пустая,
     *         если система уже автономна или уже автономизирована.
     *         Иначе — ровно {"t" -> Number(t0)}.
     *
     * Постусловие (при успешном возврате):
     *   - каждое eq.lhs — Derivative{f, 1};
     *   - если t встречалась в RHS, то t ∈ sys.functions и есть
     *     IC {t, 0, t0, t0};
     *   - все IC имеют order == 0;
     *   - исходные функции сохранены, их порядок не изменён;
     *   - исходные LHS не изменены;
     *   - возвращаемая карта содержит все введённые переменные
     *     (для текущей реализации — ровно {t} либо пусто).
     *
     * @throws AutonomizeError в случаях из описания класса AutonomizeError.
     */
    [[nodiscard]] AutonomizeAuxiliary Autonomize(RawSystem& sys);

} // namespace diffuri