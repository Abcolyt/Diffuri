// ============================================================================
// src/simplify/simplify.h
//
// Модуль simplify: алгебраическое упрощение дерева выражений.
//
// Зависимости:
//   simplify -> expression   (Expr, ExprPtr, фабрики, запросы)
//   simplify <- normalize    (нормализатор вызывает Simplify)
//
// Отвечает ТОЛЬКО за алгебру одного дерева:
//   - свёртка числовых констант (2 + 3 -> 5);
//   - нейтральные элементы (x + 0 -> x, x * 1 -> x, ...);
//   - разворачивание унарного минуса в умножение на -1;
//   - приведение подобных через каноническую форму (+ и *);
//   - канонизация Mul:
//       * CollapseRepeated: пробег одинаковых атомарных множителей
//         сворачивается в степень — x*x -> x^2, sin(x)*sin(x) -> sin(x)^2;
//       * MergePowers: Pow одной атомарной базы с числовыми целыми
//         неотрицательными показателями сливаются в один Pow —
//         x^2 * x^3 -> x^5, x * x^2 -> x^3, 2 * x^2 * x^3 -> 2 * x^5.
//         Одиночный атомарный множитель a трактуется как a^1 и участвует
//         в слиянии наравне с Pow(a, k).
//
// Что модуль НЕ делает:
//   - не знает про системы уравнений (это normalize);
//   - не делает тригонометрических/экспоненциальных тождеств;
//   - не раскладывает на множители и не выносит за скобки;
//   - не проверяет семантику (это input/normalize);
//   - не разворачивает вложенные степени Pow(Pow(a, n), m) в Pow(a, n*m)
//     — это отдельный этап канонизации, вне границ текущего;
//   - не сливает Pow с неатомарной базой (Add, Binary и т.п.),
//     даже если базы структурно равны: (x+1)^2 * (x+1)^3 остаётся как есть;
//   - не сливает Pow с разными базами и Pow с нечисловым / отрицательным /
//     дробным показателем: x^2 * y^2, x^y * x^2, x^2 * x^-1,
//     x^0.5 * x^2 — все остаются без изменений.
//
// Гарантии:
//   - результат структурно эквивалентен исходному выражению;
//   - одинаковые выражения после Simplify дают одинаковое дерево
//     (каноническая форма) — это важно для поиска подобных слагаемых;
//   - Simplify идемпотентна: Simplify(Simplify(e)) == Simplify(e)
//     для любого допустимого e. В частности, после канонизации Mul
//     в списке множителей не может остаться двух Pow одной атомарной
//     базы с числовыми целыми неотрицательными показателями —
//     все такие уже слиты в один проход.
// ============================================================================
#pragma once
#include "input/expression.h"

namespace diffuri {

    // ============================================================================
    // ОСНОВНАЯ ФУНКЦИЯ
    // ============================================================================
    /**
     * @brief Упростить дерево выражений.
     *
     * Работает рекурсивно, снизу вверх: сначала упрощаются дети, затем
     * к результату применяются правила свёртки для текущего узла.
     *
     * Возвращает новое дерево (исходное может быть частично разобрано
     * через std::move — вызывать нужно как expr = Simplify(std::move(expr))).
     *
     * Инварианты после Simplify:
     *   - нет Unary::Neg (развёрнут в Mul(-1, x));
     *   - нет Binary с двумя Number-детьми (свёрнуты в один Number);
     *   - нет лишних нейтральных элементов (0 в Add, 1 в Mul, 0 в Pow-показателе);
     *   - слагаемые в Add и множители в Mul отсортированы через Compare
     *     и объединены (подобные свернуты).
     *
     * @throws std::runtime_error при внутренних нарушениях инвариантов
     *         (например, nullptr внутри дерева — это баг, а не ошибка ввода).
     */
    [[nodiscard]] ExprPtr Simplify(ExprPtr expr);

    // ============================================================================
    // СРАВНЕНИЕ ДЕРЕВЬЕВ (для канонической формы)
    // ============================================================================
    /**
     * @brief Лексикографическое сравнение двух деревьев.
     *
     * Используется для сортировки слагаемых/множителей при приведении
     * к канонической форме. За счёт этого "x*y + y*x" и "y*x + x*y"
     * дают одинаковое дерево после Simplify.
     *
     * Порядок сравнения:
     *   1. По типу узла (Number < Function < Constant < Derivative <
     *                    Unary < Binary < Call).
     *   2. Внутри одного типа:
     *        - Number:       по значению (value);
     *        - Function:     по имени (лексикографически);
     *        - Constant:     по имени;
     *        - Derivative:   сначала по имени функции, затем по порядку;
     *        - Unary:        по op, затем по operand;
     *        - Binary:       по op, затем по lhs, затем по rhs;
     *        - Call:         по имени, затем по арности, затем по аргументам.
     *
     * Возвращает:
     *   -1  если a < b,
     *    0  если a == b (структурно идентичны),
     *   +1  если a > b.
     *
     * Сравнение строгое: разные деревья (даже алгебраически равные,
     * но не упрощённые) могут дать != 0. Поэтому Compare вызывается
     * только на уже упрощённых поддеревьях.
     */
    [[nodiscard]] int Compare(const Expr& a, const Expr& b);

    /// Структурное равенство двух деревьев (через Compare).
    [[nodiscard]] bool ExprEquals(const Expr& a, const Expr& b);

    // ============================================================================
    // ВСПОМОГАТЕЛЬНОЕ (для тестов и отладки)
    // ============================================================================
    /**
     * @brief Проверить, является ли выражение числовым литералом.
     *
     * Удобно при разборе коэффициентов: если после Simplify выражение
     * свелось к Number, его можно трактовать как константу.
     */
    [[nodiscard]] bool IsNumber(const Expr& e);

    /**
     * @brief Если выражение — Number, вернуть его значение.
     *
     * @throws std::runtime_error если e не Number.
     */
    [[nodiscard]] double AsNumber(const Expr& e);

    /**
     * @brief Разложить упрощённое выражение вида "a*x" на коэффициент и базу.
     *
     * Для Mul(Number(c), base) -> {c, base}.
     * Для Number(c)           -> {c, Number(1)}.
     * Для всего остального    -> {1.0, expr}.
     *
     * Используется нормализатором при извлечении коэффициента при
     * старшей производной.
     */
    struct CoefficientDecomposition {
        double  coefficient = 1.0;
        ExprPtr base;
    };
    [[nodiscard]] CoefficientDecomposition ExtractCoefficient(ExprPtr expr);

} // namespace diffuri