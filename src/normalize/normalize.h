// ============================================================================
// src/normalize/normalize.h
//
// Модуль normalize: разрешение системы ОДУ относительно старших производных.
//
// Зависимости:
//   normalize -> expression   (Expr, ExprPtr, фабрики, запросы)
//   normalize -> input        (RawSystem, Equation, InitialCondition)
//   normalize -> simplify     (Simplify, Compare, ExtractCoefficient)
//
// Отвечает за приведение RawSystem к каноническому виду:
//   y^(n) = RHS,   где RHS — упрощённое выражение, не содержащее y^(n).
//
// Что модуль НЕ делает:
//   - не проверяет автономность, полиномиальность, разрешимость
//     в квадратурах (это задачи последующих этапов);
//   - не занимается вводом-выводом (это input);
//   - не разбирает синтаксис (это parser).
//
// Ограничения текущего алгоритма:
//   - система должна быть линейна относительно старшей производной
//     каждой функции (иначе бросается NormalizeError);
//   - в одном уравнении — одна старшая производная (если в уравнении
//     две разные старшие — это тоже NormalizeError; разбор таких систем
//     выходит за рамки текущего этапа).
// ============================================================================
#pragma once
#include <stdexcept>
#include <string>
#include "input/input.h"

namespace diffuri {

    // ============================================================================
    // ОШИБКИ НОРМАЛИЗАЦИИ
    // ============================================================================
    /**
     * @class NormalizeError
     * @brief Семантическая ошибка, обнаруженная на этапе нормализации.
     *
     * Отличается от InputError (валидация «сырой» системы) и ParseError
     * (синтаксис). Типичные причины:
     *   - уравнение нелинейно относительно старшей производной
     *     (например, (y'')^2, sin(y''), y'' * y');
     *   - коэффициент при старшей производной равен нулю после свёртки
     *     (уравнение вырождается и не разрешимо относительно неё);
     *   - в одном уравнении несколько разных старших производных
     *     (например, x'' + y'' = t — система требует перестройки).
     */
    class NormalizeError : public std::runtime_error {
    public:
        explicit NormalizeError(const std::string& what);
    };

    // ============================================================================
    // ОСНОВНАЯ ФУНКЦИЯ
    // ============================================================================
    /**
     * @brief Привести систему к каноническому виду: y^(n) = RHS.
     *
     * Алгоритм (для каждого уравнения):
     *   1. Упростить lhs и rhs через Simplify.
     *   2. Определить целевую функцию уравнения — ту неизвестную, чья
     *      старшая производная встречается в уравнении.
     *   3. Найти суммарный коэффициент C при этой старшей производной
     *      (с учётом знаков и переноса между lhs и rhs).
     *   4. Проверить линейность: старшая производная должна входить
     *      только как C * y^(n) (не в степени, не внутри функций,
     *      не в произведении с другой функцией).
     *   5. Перенести все слагаемые без y^(n) в rhs с инвертированным знаком.
     *   6. Поделить rhs на C (умножить на 1/C).
     *   7. Заменить lhs на MakeDerivative(function_name, n).
     *   8. Вызвать Simplify для итогового rhs.
     *
     * Порядок обработки уравнений — в порядке их появления в sys.equations.
     * Начальные условия не меняются (они уже в канонической форме).
     *
     * @param sys Система. Модифицируется на месте.
     * @throws NormalizeError если какое-то уравнение не удаётся разрешить.
     *
     * Постусловие: для каждого уравнения eq после вызова:
     *   - eq.lhs — это Derivative{function_name, n};
     *   - eq.rhs — упрощённое выражение, в котором нет Derivative
     *     с порядком >= n для этой функции.
     */
    void NormalizeSystem(RawSystem& sys);

    // ============================================================================
    // ВСПОМОГАТЕЛЬНЫЕ ФУНКЦИИ (для тестов и повторного использования)
    // ============================================================================
    /**
     * @brief Проверить, линейно ли выражение по данной производной.
     *
     * «Линейно» означает: производная встречается только в слагаемых вида
     *   C * f^(k), где C — выражение, не содержащее f^(k).
     *
     * Не-линейные случаи:
     *   - (y'')^2;
     *   - sin(y'');
     *   - y'' * y'';
     *   - y'' * x  (где x — та же функция, т.е. x = y).
     *
     * @param expr       Дерево выражения.
     * @param func_name  Имя функции.
     * @param order      Порядок производной, линейность по которой проверяется.
     */
    [[nodiscard]] bool IsLinearIn(const Expr& expr,
        const std::string& func_name,
        int order);

    /**
     * @brief Извлечь суммарный коэффициент при заданной производной.
     *
     * Считает сумму коэффициентов во всех слагаемых, содержащих
     * Derivative{func_name, order}. Выражение должно быть упрощено
     * (Simplify) и линейно по этой производной.
     *
     * @throws NormalizeError если выражение не линейно.
     */
    [[nodiscard]] double TotalCoefficient(const Expr& expr,
        const std::string& func_name,
        int order);

    /**
     * @brief Определить целевую функцию уравнения.
     *
     * Возвращает имя функции, старшая производная которой встречается
     * в уравнении. Если таких функций несколько — бросает NormalizeError.
     * Если не встречается ни одной — бросает NormalizeError (уравнение
     * без неизвестных — это либо тавтология, либо противоречие; оба случая
     * должны быть отловлены раньше, на валидации, но здесь — страховка).
     */
    [[nodiscard]] std::string TargetFunction(const Equation& eq,
        const RawSystem& sys);

} // namespace diffuri