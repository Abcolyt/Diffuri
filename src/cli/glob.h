// ============================================================================
// src/cli/glob.h
//
// Модуль cli/glob: раскрытие масок файловых имён ('*' и '?') в список путей.
//
// Зависимости:
//   glob -> (только std)
//
// Отвечает за:
//   - проверку, содержит ли путь маску;
//   - раскрытие маски в отсортированный список файлов;
//   - генерацию выходного имени с суффиксом (для --trajectory / --log
//     при работе с несколькими входными файлами).
//
// Что модуль НЕ делает:
//   - не читает содержимое файлов (это input);
//   - не запускает пайплайн (это main / pipeline/runner).
//
// Поддерживаемые метасимволы:
//   '*'   — любая последовательность символов (в пределах одного имени);
//   '?'   — ровно один символ.
//
// Рекурсивный '**' НЕ поддерживается: подкаталоги не обходятся.
// Этого достаточно для сценария «все .txt из одной папки».
//
// Windows cmd.exe сам не раскрывает маски, поэтому раскрытие делаем здесь,
// а не полагаемся на shell. Одна и та же команда с '*' работает в cmd,
// PowerShell и bash одинаково.
// ============================================================================
#pragma once

// --- Стандартная библиотека ---
#include <string>
#include <vector>

