// ============================================================================
// src/cli/settings.h
//
// Модуль cli/settings: чтение и запись пользовательских настроек
// (значения по умолчанию для CliOptions), применяемых при запуске
// в интерактивном режиме.
//
// Зависимости:
//   settings -> cli (CliOptions)
//
// Отвечает за:
//   - загрузку настроек из текстового файла (key = value);
//   - сохранение текущих настроек обратно в файл;
//   - создание файла со значениями по умолчанию при первом запуске;
//   - нормализацию конвенции stdin: значения "-" и "" для ключа input
//     оба означают «читать систему из stdin» и хранятся как пустая строка.
//
// Что модуль НЕ делает:
//   - не парсит аргументы командной строки (это ParseCliArgs);
//   - не показывает TUI-экран (это PromptSettings).
//
// Формат файла:
//   key = value, по одной паре на строку. Строки, начинающиеся с '#',
//   игнорируются. Неизвестные ключи и синтаксические огрехи попадают
//   в warning, не прерывая загрузку.
//
// Конвенция stdin (ключ input):
//   input = path/to/file.txt  — читать систему из файла;
//   input = -                 — читать систему из stdin (как пусто);
//   input =                   — то же самое, что "-".
//   В CliOptions::input_path это всегда пустая строка (каноническая форма
//   «нет файла»). SaveSettings пишет "-", а не пустое место — так в файле
//   видно, что выбрано осознанно.
// ============================================================================
#pragma once

// --- Стандартная библиотека ---
#include <string>

// --- Внутренние зависимости ---
#include "cli/cli.h"

namespace diffuri {

    // ============================================================================
    // 1. ОПЦИИ И КОНФИГУРАЦИЯ
    // ============================================================================

    /**
     * @struct SettingsLoadResult
     * @brief Результат загрузки файла настроек.
     */
    struct SettingsLoadResult {
        bool        file_existed = false;    ///< Был ли файл на диске.
        bool        created_default = false; ///< Был ли создан файл со значениями по умолчанию.
        std::string path;                    ///< Фактический путь к файлу.
        std::string warning;                 ///< Нефатальные предупреждения парсера (пусто, если всё ок).
    };

    // ============================================================================
    // 2. СТРУКТУРЫ ДАННЫХ
    // ============================================================================
    // (В этом модуле нет отдельных структур данных)

    // ============================================================================
    // 3. ИСКЛЮЧЕНИЯ
    // ============================================================================
    // (В этом модуле исключения не бросаются: ошибки ввода-вывода и опечатки
    //  в ключах возвращаются через SettingsLoadResult::warning)

    // ============================================================================
    // 4. ПУБЛИЧНЫЙ API (свободные функции)
    // ============================================================================

    /**
     * @brief Путь к файлу настроек по умолчанию.
     *
     * Относительный, разрешается от CWD — так же, как data/constants.txt
     * в parser. Это значит, что при запуске из папки сборки файл найдётся
     * рядом с бинарником.
     *
     * @return "data/settings.txt".
     */
    [[nodiscard]] std::string DefaultSettingsPath();

    /**
     * @brief Прочитать файл настроек и наложить значения на opts.
     *
     * Если файла нет — создаёт его со значениями из opts (текущие дефолты)
     * и выставляет created_default = true. Это и есть «первый запуск»:
     * пользователь получает готовый файл, который можно править.
     *
     * Неизвестные ключи и синтаксические огрехи попадают в warning, не
     * прерывая загрузку. Отсутствие прав на запись — тоже warning, не ошибка.
     *
     * Для ключа input значение "-" и пустое значение оба нормализуются
     * в пустую строку opts.input_path (каноническое представление stdin).
     *
     * @param path Путь к файлу настроек.
     * @param opts Опции, которые нужно дополнить/переопределить.
     * @return     Результат загрузки.
     */
    [[nodiscard]] SettingsLoadResult LoadSettings(const std::string& path,
        CliOptions& opts);

    /**
     * @brief Сохранить текущие настройки в файл.
     *
     * Best-effort: если файл не открылся на запись — молча выходим
     * (настройки не критичны для работы). Используется при первом запуске
     * для создания файла по умолчанию и опционально после TUI.
     *
     * Для ключа input пустая строка opts.input_path пишется как "-"
     * (осознанное «читать из stdin»), непустая — как есть.
     *
     * @param path Путь к файлу.
     * @param opts Опции для записи.
     */
    void SaveSettings(const std::string& path, const CliOptions& opts);

} // namespace diffuri