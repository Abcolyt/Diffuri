// ============================================================================
// src/order_reducer/order_reducer.h
//
// Модуль order_reducer: приведение нормализованной системы ОДУ
// y^(n) = RHS к системе первого порядка.
//
// Зависимости:
//   order_reducer -> expression   (Expr, ExprPtr, фабрики)
//   order_reducer -> input        (RawSystem, Equation, InitialCondition,
//                                  DerivativeOrders)
//
// Отвечает за:
//   - приведение нормализованной системы ОДУ к системе первого порядка;
//   - введение вспомогательных переменных для производных порядка > 1;
//   - перенос начальных условий старших порядков на новые переменные.
//
// Что модуль НЕ делает:
//   - не нормализует систему (это NormalizeSystem);
//   - не полиномизирует (это следующий этап пайплайна);
//   - не трогает систему, которая уже первого порядка;
//   - не обрабатывает символьные IC (значения IC — double).
//
// ВАЖНО: ReduceOrder предполагает, что система уже нормализована
// (каждое eq.lhs — это Derivative). Если это не так — OrderReducerError.
// ============================================================================
#pragma once

// --- Стандартная библиотека ---
#include <map>
#include <stdexcept>
#include <string>

// --- Внутренние зависимости ---
#include "core/expression.h"
#include "input/input.h"

namespace diffuri {

    // ============================================================================
    // 1. ОПЦИИ И КОНФИГУРАЦИЯ
    // ============================================================================
    // (В этом модуле нет структур опций)

    // ============================================================================
    // 2. СТРУКТУРЫ ДАННЫХ
    // ============================================================================

    /**
     * @brief Карта {имя_новой_переменной → её определение}.
     *
     * Ключ — имя вспомогательной переменной в терминах исходных функций:
     *   "x_1"  → Derivative{"x", 1}
     *   "x_2"  → Derivative{"x", 2}
     *
     * Используется PipelineTrace для диагностики и (в будущем) обратной
     * подстановки при реконструкции «чистого» вида системы.
     * Для систем, уже бывших первого порядка, карта пуста.
     */
    using ReduceOrderAuxiliary = std::map<std::string, ExprPtr>;

    // ============================================================================
    // 3. ИСКЛЮЧЕНИЯ
    // ============================================================================

    /**
     * @class OrderReducerError
     * @brief Ошибка этапа понижения порядка.
     *
     * Типичные причины:
     *   - lhs уравнения не Derivative (система не была нормализована);
     *   - коллизия имён вспомогательных переменных не разрешается
     *     префиксом "_" (и f_1, и _f_1 уже заняты);
     *   - IC имеет order > max_order(f) — согласованность нарушена.
     */
    class OrderReducerError : public std::runtime_error {
    public:
        explicit OrderReducerError(const std::string& what);
    };

    // ============================================================================
    // 4. ПУБЛИЧНЫЙ API (свободные функции)
    // ============================================================================

    /**
     * @brief Привести систему к первому порядку. Модифицирует sys in-place.
     *
     * Для каждой функции f со старшим порядком n = DerivativeOrders(sys)[f]:
     *   - при n == 1 функция не затрагивается;
     *   - при n > 1 вводятся вспомогательные функции f_1..f_{n-1},
     *     исходное уравнение заменяется цепочкой первого порядка,
     *     а IC старших порядков переименовываются в IC новых переменных.
     *
     * Имена новых переменных: f_1, f_2, ... Если хотя бы одно из них
     * уже занято в sys.functions — используется префикс "_" для всех имён
     * этой функции сразу: _f_1, _f_2, ... Если и они заняты — ошибка.
     *
     * @param sys Система. Модифицируется на месте.
     *
     * @return Карта {имя_новой_переменной → её определение}. Пустая, если
     *         понижать было нечего.
     *
     * Постусловие (при успешном возврате):
     *   - каждое eq.lhs — Derivative{func, 1};
     *   - для каждой функции из sys.functions есть ровно одно уравнение
     *     с lhs = Derivative{func, 1};
     *   - все IC имеют order == 0;
     *   - sys.functions содержит все исходные имена плюс новые.
     *
     * @throws OrderReducerError при нарушении входных инвариантов
     *         (см. описание класса OrderReducerError).
     */
    [[nodiscard]] ReduceOrderAuxiliary ReduceOrder(RawSystem& sys);

} // namespace diffuri