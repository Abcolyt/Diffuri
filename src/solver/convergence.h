// ============================================================================
// src/solver/convergence.h
//
// Модуль convergence: априорные оценки радиуса сходимости и обратные
// функции остатков ряда Тейлора по статье
// [Бабаджанянц, Большаков 2012] §1.3.2, §2.1.1, §2.1.2.
//
// Зависимости:
//   (только .cpp) convergence -> taylor_spec   (TaylorSpec)
//
// Что модуль НЕ делает:
//   - не выбирает h (это step_control);
//   - не выбирает M (это order_control);
//   - не оценивает локальную погрешность (это error_control).
//
// Реализует:
//   - масштабирующие множители α_i (§2.1.2 статьи) — MVP-компромисс:
//     α_i = max(|x_i|, 1); полная оптимизационная задача нелинейна, и
//     готового решения в открытом доступе нет;
//   - ρ(α) — радиус сходимости ряда Тейлора:
//       линейный случай  (§1.3.2.1): ρ = 1 / max_i s_i(α),
//         s_i(α) = α_i^{-1} Σ_j α_j |a_{ij}|;
//       нелинейный случай (§1.3.2.2): ρ = 1 / (L · s(α)),
//         L = max_deg − 1,
//         s_j(α) = α_j^{-1} (|a_j| + Σ_{m=1}^{L+1} Σ_{|i|=m} α^i |a_{j i}|);
//   - u⁻¹, v⁻¹ — обратные функции остатков ряда (§2.1.1):
//       u(τ) = e^τ − T_M e^τ,               M — параметр (задача 2.1);
//       v(τ) = b(τ) − T_M b(τ),             M, L — параметры (задача 2.2);
//       b(τ) = (1−τ)^(−1/L).
//     Обратные функции вычисляются численно (бисекция, 60 итераций);
//   - CalculateTau — априорный безразмерный шаг τ из §2.1.2 (задача 2.3):
//       линейная система  → InverseU(rtol, M);
//       нелинейная        → CalculateInverseV(rtol, M, L), L = max_deg − 1.
//     Результат дополнительно зажат сверху значением kMaxSafeTau < 1
//     (см. doxygen CalculateTau): запас компенсирует численную погрешность ρ.
//     Полная форма min_j(|x_j|+Δ)/α_j отложена, x и α оставлены
//     в сигнатуре как точка расширения.
// ============================================================================
#pragma once

// --- Стандартная библиотека ---
#include <cstddef>
#include <vector>

namespace diffuri {

    // Forward-declaration: используется только по ссылке в ConvergenceRadius.
    struct TaylorSpec;

    // ============================================================================
    // 1. ОПЦИИ И КОНФИГУРАЦИЯ
    // ============================================================================
    // (В этом модуле нет структур опций)

    // ============================================================================
    // 2. СТРУКТУРЫ ДАННЫХ
    // ============================================================================
    // (В этом модуле нет структур данных)

    // ============================================================================
    // 3. ИСКЛЮЧЕНИЯ
    // ============================================================================
    // (В этом модуле нет специфичных исключений)

    // ============================================================================
    // 4. ПУБЛИЧНЫЙ API (свободные функции)
    // ============================================================================

    /**
     * @brief Вычислить масштабирующие множители α_i по текущему состоянию.
     *
     * MVP-компромисс (§2.1.2 статьи): α_i = max(|x_i|, 1.0).
     * Полная задача — минимизация max_j s_j(α) при α_j ≥ 1 — нелинейна;
     * её решение в открытом доступе отсутствует, поэтому здесь используется
     * упрощённая формула. При max_j |x_j| == 0 возвращается вектор единиц.
     *
     * @param x Вектор состояния (размер n).
     * @return  Вектор α того же размера.
     */
    [[nodiscard]] std::vector<double> CalculateScalingMultipliers(const std::vector<double>& x);

    /**
     * @brief Радиус сходимости ρ(α) ряда Тейлора в текущей точке.
     *
     * Линейный случай (§1.3.2.1): ρ(α) = 1 / max_i s_i(α),
     *   s_i(α) = α_i^{-1} Σ_{j=1}^{n} α_j |a_{ij}|.
     * Нелинейный случай (§1.3.2.2): ρ(α) = 1 / (L · s(α)),
     *   s_j(α) = α_j^{-1} (|a_j| + Σ_{m=1}^{L+1} Σ_{|i|=m} α^i |a_{j i}|),
     *   L = max_deg − 1, max_deg — максимальная степень монома в RHS.
     *
     * Система считается линейной, если в TaylorSpec нет нелинейных мономов
     * (u == n). Если s(α) == 0 — возвращается +∞.
     *
     * @param spec  Спецификация системы.
     * @param alpha Масштабирующие множители (размер n).
     * @return      Радиус сходимости ρ.
     */
    [[nodiscard]] double CalculateConvergenceRadius(const TaylorSpec& spec,
        const std::vector<double>& alpha);

    /**
     * @brief Обратная функция u⁻¹ (линейный случай).
     *
     * u(τ) = e^τ − T_M e^τ (§1.3.2.1, формула (7)),
     * где M — порядок метода.
     * Решение u(τ) = tolerance ищется бисекцией на [0, 1]
     * (60 итераций, точность ~1e-18).
     * При tolerance ≤ 0 возвращает 0; при tolerance ≥ u(1, M) — 1.
     *
     * @param tolerance Целевое значение остатка u(τ).
     * @param M         Порядок метода (число удерживаемых членов ряда).
     * @return          Значение τ.
     */
    [[nodiscard]] double CalculateInverseU(double tolerance, std::size_t M);

    /**
     * @brief Обратная функция v⁻¹ (нелинейный полиномиальный случай).
     *
     * v(τ) = b(τ) − T_M b(τ), где b(τ) = (1−τ)^(−1/L)
     * (§1.3.2.2, формула (8)); M — порядок метода, L — параметр
     * b-функции.
     *
     * Для L = 1 (квадратичная система после Quadratize) используется
     * замкнутая форма v(τ) = τ^(M+1) / (1 − τ), численно устойчивая
     * при малых τ. Для L > 1 — прямое суммирование хвоста ряда:
     *   v(τ) = Σ_{m=M+1}^∞ c_m τ^m,
     *   c_0 = 1,  c_m = c_{m−1} · (1/L + m − 1) / m.
     *
     * Решение v(τ) = tolerance ищется бисекцией (60 итераций).
     * При tolerance ≤ 0 возвращает 0; для очень больших tolerance — 1.
     *
     * @param tolerance Целевое значение остатка v(τ).
     * @param M         Порядок метода.
     * @param L         Параметр b-функции (L = max_deg − 1 для нелин.
     *                  системы; после Quadratize всегда L = 1).
     * @return          Значение τ.
     */
    [[nodiscard]] double CalculateInverseV(double tolerance,
        std::size_t M,
        std::size_t L);

    /**
     * @brief Априорный безразмерный шаг τ из §2.1.2 статьи (задача 2.3).
     *
     * Принятая в проекте интерпретация (утверждена заказчиком):
     *   линейная система (spec.u == spec.n):
     *       τ = CalculateInverseU(rtol, M);
     *   нелинейная (после Quadratize):
     *       τ = CalculateInverseV(rtol, M, L), L = max_deg − 1,
     *       max_deg — максимальная степень монома в spec.monomial_keys.
     *
     * Полная форма §2.1.2
     *     τ = min_j (|x_j| + Δ) / α_j
     * НЕ используется: при χ_i = α_i (наш случай) Утверждения 2 и 4
     * сводятся к чистому rtol как аргументу обратной функции. Если на
     * практике h_a окажется систематически меньше h_b и §2.1.2 не даст
     * эффекта — вернёмся к полной форме отдельным ТЗ.
     *
     * Результат всегда в [0, kMaxSafeTau] с kMaxSafeTau = 1 − 1e-12.
     * Верхний предел НЕ 1.0: ρ вычисляется численно из s(α) с
     * относительной погрешностью ~1e-14 (сумма K_j слагаемых, каждое
     * 0.5 ulp). Стоять точно на границе круга сходимости рискованно:
     * теорема §1.3.2.1 гарантирует сходимость при |t − t0| ≤ ρ
     * в точной арифметике, а мы применяем её в double. Запас 1e-12
     * даёт ~100× над погрешностью ρ и теряет 1e-12 относительной
     * длины шага.
     *
     * Радиус сходимости ρ подставляется снаружи: h_a = τ · ρ —
     * ответственность step_control::PickStep.
     *
     * @param spec  Спецификация системы (решает, U или V).
     * @param x     Текущее состояние. НЕ используется (точка расширения
     *              для полной формы min_j(...)).
     * @param alpha Масштабирующие множители. НЕ используются (там же).
     * @param rtol  Относительная точность (аргумент обратной функции).
     * @param M     Порядок метода.
     * @return      Безразмерный шаг τ ∈ [0, 1 − 1e-12].
     */
    [[nodiscard]] double CalculateTau(const TaylorSpec& spec,
        const std::vector<double>& x,
        const std::vector<double>& alpha,
        double rtol,
        std::size_t M);

} // namespace diffuri