// ============================================================================
// src/solver/convergence.h
//
// Модуль convergence: априорные оценки радиуса сходимости и обратные
// функции остатков ряда Тейлора по статье
// [Бабаджанянц, Большаков 2012] §1.3.2, §2.1.1, §2.1.2.
//
// Зависимости:
//   (только .cpp) convergence -> taylor_spec   (TaylorSpec)
//
// Что модуль НЕ делает:
//   - не выбирает h (это step_control);
//   - не выбирает M (это order_control);
//   - не оценивает локальную погрешность (это error_control).
//
// Реализует:
//   - масштабирующие множители α_i (§2.1.2 статьи) — MVP-компромисс:
//     α_i = max(|x_i|, 1); полная оптимизационная задача нелинейна, и
//     готового решения в открытом доступе нет;
//   - ρ(α) — радиус сходимости ряда Тейлора:
//       линейный случай  (§1.3.2.1): ρ = 1 / max_i s_i(α),
//         s_i(α) = α_i^{-1} Σ_j α_j |a_{ij}|;
//       нелинейный случай (§1.3.2.2): ρ = 1 / (L · s(α)),
//         L = max_deg − 1,
//         s_j(α) = α_j^{-1} (|a_j| + Σ_{m=1}^{L+1} Σ_{|i|=m} α^i |a_{j i}|);
//   - u⁻¹, v⁻¹ — обратные функции остатков ряда (§2.1.1):
//       u(τ) = e^τ − T_M e^τ,
//       v(τ) = b(τ) − T_M b(τ), b(τ) = (1−τ)^(−1/L).
//     В текущей сигнатуре нет M и L; зафиксированы M = 20, L = 1
//     (солвер работает с квадратичными системами после Quadratize).
//     Обратные функции вычисляются численно (бисекция, 60 итераций,
//     ~1e-18 по τ), что избавляет от таблиц из [29].
// ============================================================================
#pragma once

#include <vector>

namespace diffuri {

    // Fwd: используется только по ссылке в ConvergenceRadius.
    struct TaylorSpec;

    /**
     * @brief Вычислить масштабирующие множители α_i по текущему состоянию.
     *
     * MVP-компромисс (§2.1.2 статьи): α_i = max(|x_i|, 1.0).
     * Полная задача — минимизация max_j s_j(α) при α_j ≥ 1 — нелинейна;
     * её решение в открытом доступе отсутствует, поэтому здесь используется
     * упрощённая формула. При max_j |x_j| == 0 возвращается вектор единиц.
     *
     * @param x Вектор состояния (размер n).
     * @return Вектор α того же размера.
     */
    [[nodiscard]] std::vector<double> ScalingMultipliers(const std::vector<double>& x);

    /**
     * @brief Радиус сходимости ρ(α) ряда Тейлора в текущей точке.
     *
     * Линейный случай (§1.3.2.1): ρ(α) = 1 / max_i s_i(α),
     *   s_i(α) = α_i^{-1} Σ_{j=1}^{n} α_j |a_{ij}|.
     * Нелинейный случай (§1.3.2.2): ρ(α) = 1 / (L · s(α)),
     *   s_j(α) = α_j^{-1} (|a_j| + Σ_{m=1}^{L+1} Σ_{|i|=m} α^i |a_{j i}|),
     *   L = max_deg − 1, max_deg — максимальная степень монома в RHS.
     *
     * Система считается линейной, если в TaylorSpec нет нелинейных мономов
     * (u == n). Если s(α) == 0 — возвращается +∞.
     *
     * @param spec  Спецификация системы.
     * @param alpha Масштабирующие множители (размер n).
     */
    [[nodiscard]] double ConvergenceRadius(const TaylorSpec& spec,
        const std::vector<double>& alpha);

    /**
     * @brief Обратная функция u⁻¹ (линейный случай).
     *
     * u(τ) = e^τ − T_M e^τ, M = 20. Решение u(τ) = tolerance
     * ищется бисекцией на [0, 1] (60 итераций, точность ~1e-18).
     * При tolerance ≤ 0 возвращает 0; при tolerance ≥ u(1) — 1.
     *
     * @param tolerance Целевое значение остатка u(τ).
     */
    [[nodiscard]] double InverseU(double tolerance);

    /**
     * @brief Обратная функция v⁻¹ (нелинейный полиномиальный случай).
     *
     * v(τ) = b(τ) − T_M b(τ), b(τ) = (1−τ)^(−1/L), M = 20, L = 1.
     * Для L = 1 имеем замкнутую форму v(τ) = τ^(M+1) / (1 − τ).
     * Решение v(τ) = tolerance ищется бисекцией (60 итераций).
     * При tolerance ≤ 0 возвращает 0; для очень больших tolerance — 1.
     *
     * @param tolerance Целевое значение остатка v(τ).
     */
    [[nodiscard]] double InverseV(double tolerance);

} // namespace diffuri