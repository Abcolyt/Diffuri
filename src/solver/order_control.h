// ============================================================================
// src/solver/order_control.h
//
// Модуль order_control: выбор порядка M. В MVP — no-op.
//
// Зависимости:
//   order_control -> taylor_table   (TaylorTable)
//   order_control -> solver         (SolveOptions)
//
// Что модуль НЕ делает:
//   - никакой градуировки;
//   - никакой адаптации.
//
// MVP-поведение:
//   - всегда возвращает M_current;
//   - если M_current == 0, возвращает литерал 20.
//
// Параметры h и H переданы для совместимости с алгоритмом 2.3 статьи
// [Бабаджанянц, Большаков 2012]:
//   - h — текущий шаг;
//   - H — шаг на момент последней смены M.
// Алгоритм 2.3 переключает M, когда h изменился относительно H
// в m раз (m = 5 в статье). В MVP эти параметры не используются.
//
// Точка расширения: в итерации 3 здесь появятся алгоритмы 2.1.5, 2.1.6,
// 2.3 из статьи.
// ============================================================================
#pragma once

#include <cstddef>

#include "solver/solver.h"
#include "solver/taylor_table.h"

namespace diffuri {

    /**
     * @brief Выбрать порядок M для следующего шага.
     *
     * MVP: возвращает M_current, если M_current != 0; иначе — 20.
     *
     * @param table Таблица Тейлора для текущей точки (в MVP не используется).
     * @param M     Текущий порядок метода.
     * @param h     Текущий шаг (в MVP не используется).
     * @param H     Шаг на момент последней смены M (в MVP не используется).
     * @param opts  Опции интегрирования.
     */
    [[nodiscard]] std::size_t PickOrder(const TaylorTable& table,
        std::size_t M,
        double h,
        double H,
        const SolveOptions& opts);

} // namespace diffuri