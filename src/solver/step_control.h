    /**
     * @brief Вычислить оптимальный размер следующего шага интегрирования.
     *
     * @param table  Таблица Тейлора, построенная в текущей точке.
     * @param spec   Спецификация системы (используется для априорных оценок).
     * @param h_old  Размер предыдущего (пробного) шага.
     * @param M      Текущий порядок метода рядов Тейлора.
     * @param opts   Опции интегрирования (допуски rtol/atol и границы h_min/h_max).
     * @return       Размер следующего шага, зажатый в [opts.h_min, opts.h_max].
     * @throws SolverError Если итеративная коррекция не сходится за лимит итераций
     *         (признак вырожденности системы или некорректной оценки погрешности).
     */
