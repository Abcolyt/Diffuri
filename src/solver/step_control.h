// ============================================================================
// src/solver/step_control.h
//
// Модуль step_control: адаптивный выбор шага интегрирования h.
//
// Архитектура базируется на комбинации априорных и апостериорных оценок из
// статьи [Бабаджанянц, Большаков 2012], «Вычислительные методы и
// программирование», т. 13, с. 497–510:
//   1. Априорный шаг (§2.1.2): prior_step = τ · ρ.
//      Гарантирует, что шаг лежит строго внутри радиуса сходимости ряда.
//   2. Апостериорный шаг (§2.1.4): posterior_step = h_old · (1 / ε(h_old))^{1/(M+1)}.
//      Пытается угадать шаг, дающий погрешность ровно ε = 1.
//   3. Итеративная коррекция (§2.1.3): поиск от max(prior, posterior)
//      до фактической границы ε(h) = 1.
//
// Финальная формула сборки (§2.2 + страховка):
//   h_new = clamp(min(IterativeCorrection(max(prior, posterior)),
//                     kMaxGrowthFactor · h_old),
//                 h_min, h_max).
//
// Ограничение роста (kMaxGrowthFactor = 2.0) оставлено как принудительная
// страховка. В полной версии статьи оно компенсируется алгоритмом §2.3
// (автоматическое переключение порядка M при резком изменении шага).
// Поскольку §2.3 в текущей версии не реализован (M фиксирован), резкий скачок
// шага в 10× может привести к потере глобальной точности. Кап в 2.0
// предотвращает это.
//
// Зависимости:
//   step_control -> error_control  (CalculateErrorEstimate)
//   step_control -> convergence    (CalculateScalingMultipliers, CalculateConvergenceRadius,
//                                   CalculateTau)
//   step_control -> taylor_table   (TaylorTable::X0)
//   step_control -> taylor_spec    (TaylorSpec)
//   step_control -> solver         (SolveOptions, SolverError)
// ============================================================================
