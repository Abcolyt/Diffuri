// ============================================================================
// src/solver/taylor_spec.h
//
// Модуль taylor_spec: превратить RawSystem в неизменяемую структуру,
// задающую рекуррентные формулы метода рядов Тейлора (T, S, a).
//
// Зависимости:
//   taylor_spec -> input    (RawSystem)
//   (только .cpp) taylor_spec -> solver   (SolverError)
//
// Отвечает за:
//   - сбор всех мономов из RHS: свободные члены, линейные, квадратичные;
//   - уникализацию мономов через канонический ключ;
//   - упорядочивание мономов по возрастанию степени, присвоение
//     индексов 0 … u;
//   - построение схемы S: для каждого x_k (k > n) пары (p(k), q(k));
//   - построение коэффициентов a[j][l] в разреженном формате.
//
// Что модуль НЕ делает:
//   - никаких численных вычислений (это taylor_table);
//   - не проверяет автономность/полиномиальность (это выше по пайплайну);
//   - не трогает исходный RawSystem.
//
// Время жизни: строится один раз при старте Solve.
// ============================================================================
#pragma once

#include <cstddef>
#include <map>
#include <string>
#include <utility>
#include <vector>

#include "input/input.h"

namespace diffuri {

    // Fwd: SolverError бросается из .cpp, в сигнатурах этого заголовка не участвует.
    class SolverError;

    /**
     * @struct TaylorSpec
     * @brief Неизменяемая спецификация рекуррентных формул метода Тейлора.
     *
     * Соответствует обозначениям статьи [Бабаджанянц, Большаков 2012]:
     *   T = (x^{i(1)}, ..., x^{i(n)}, x^{i(n+1)}, ..., x^{i(u)}) — набор мономов,
     *   пронумерованных 0 … u; индекс 0 зарезервирован под константу 1.
     *   S = {(p(k), q(k)) | k ∈ [n+1 : u]} — схема разложения нелинейного
     *   монома x_k = x_{p(k)} · x_{q(k)}.
     *   a[j][l] — коэффициент при x^{i(l)} в правой части dx_j/dt.
     *
     * Индексация (0-based, согласована с monomial_keys):
     *   0        — константа 1 (свободный член);
     *   1 … n    — исходные функции системы (x_1, ..., x_n);
     *   n+1 … u  — нелинейные (квадратичные) мономы.
     *
     * Соответствие с формулами статьи: 1-based индекс i из статьи
     * соответствует нашему i-1. В частности, a.size() == n, где a[j]
     * относится к функции function_names[j] (то есть x_{j+1}).
     *
     * Для MVP мономы имеют степень ≤ 2: система должна быть квадратизирована
     * заранее (Polynomize + Quadratize).
     */
    struct TaylorSpec {
        /// Число исходных функций.
        std::size_t n = 0;

        /// Наибольший индекс монома; всего мономов u+1 (индекс 0 — константа).
        std::size_t u = 0;

        /// Имена исходных функций в порядке sys.functions.
        /// function_names[j] соответствует x_{j+1}.
        std::vector<std::string> function_names;

        /// Канонические ключи мономов. monomial_keys[0] == "1".
        /// Для линейных мономов — имя функции; для квадратичных — канонический
        /// ключ вида "x*y" (множители отсортированы).
        std::vector<std::string> monomial_keys;

        /// Схема S: для k ∈ [n+1 : u] scheme[k] = {p, q}, где
        /// x_k = x_{p} · x_{q}. Для k ≤ n — пустая пара.
        std::vector<std::pair<std::size_t, std::size_t>> scheme;

        /// Разреженные коэффициенты: a[j][l] — коэффициент при x^{i(l)}
        /// в правой части dx_j/dt.
        /// Размер a — n (индексация 0-based по j).
        /// Ключи внутренней map — индексы мономов l ∈ [0 : u], согласованы
        /// с monomial_keys.
        std::vector<std::map<std::size_t, double>> a;
    };

    /**
     * @brief Построить TaylorSpec из системы.
     *
     * @param sys Система (обычно после Polynomize + Quadratize).
     *            Не модифицируется.
     *
     * @throws SolverError если:
     *   - хотя бы одно уравнение не имеет вида Derivative{f, 1} = RHS;
     *   - RHS содержит моном степени > 2;
     *   - RHS содержит Call, Unary, Div, Pow с нецелым/отрицательным
     *     показателем (страховка; должно быть отсеяно выше по пайплайну).
     */
    [[nodiscard]] TaylorSpec BuildTaylorSpec(const RawSystem& sys);

} // namespace diffuri